"""Builds config/instruments.csv - the instrument catalogue the platform imports (roadmap P3.1.01).

Sources:
  config/universes/*.toml
      ticker, name, listing exchange, currency - written by hand
  spikes/ibkr-feasibility/out/contracts.csv
      IBKR contract details of spike B: contract id, primary exchange, ISIN
      (git-ignored run output; public reference data, nothing of the account)

An instrument enters the catalogue only when IBKR confirmed its contract and the exchange named
in the universe file agrees with IBKR's primary exchange. Everything else is listed as skipped,
with the reason.

    uv run python tools/make_instrument_catalogue.py            (from python/)
    uv run python tools/make_instrument_catalogue.py --check    fails when out of date

The platform reads the result with `ITrade.Host import-instruments config/instruments.csv`;
importing it again changes nothing.
"""

from __future__ import annotations

import argparse
import csv
import io
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
UNIVERSES = ROOT / "config" / "universes"
CONTRACTS = ROOT / "spikes" / "ibkr-feasibility" / "out" / "contracts.csv"
CATALOGUE = ROOT / "config" / "instruments.csv"

HEADER = ("ticker", "exchange", "currency", "name", "isin", "ibkr_con_id")
NOTE = (
    "# Instrument catalogue. Generated by python/tools/make_instrument_catalogue.py from "
    "config/universes/*.toml and IBKR contract details - do not edit by hand."
)


def candidates() -> dict[str, dict[str, str]]:
    """Ticker -> name, listing and currency from every universe file (first file wins)."""
    found: dict[str, dict[str, str]] = {}
    for path in sorted(UNIVERSES.glob("*.toml")):
        with path.open("rb") as f:
            universe = tomllib.load(f)
        currency = universe.get("universe", {}).get("currency", "")
        for item in universe.get("candidates", []):
            found.setdefault(
                item["ticker"],
                {"name": item["name"], "listing": item.get("listing", ""), "currency": currency},
            )
    return found


def contracts() -> dict[str, dict[str, str]]:
    with CONTRACTS.open(newline="", encoding="utf-8") as f:
        return {row["ticker"]: row for row in csv.DictReader(f)}


def build() -> tuple[str, list[str]]:
    """The catalogue text and the reasons for every candidate left out."""
    details = contracts()
    rows, skipped = [], []
    for ticker, item in sorted(candidates().items()):
        contract = details.get(ticker)
        if contract is None:
            skipped.append(f"{ticker}: no IBKR contract details")
        elif contract["error"] or not contract["con_id"]:
            skipped.append(
                f"{ticker}: IBKR did not confirm the contract ({contract['error'] or 'no id'})"
            )
        elif contract["primary_exchange"] != item["listing"]:
            skipped.append(
                f"{ticker}: universe file says {item['listing']}, "
                f"IBKR says {contract['primary_exchange']}"
            )
        else:
            rows.append(
                (
                    ticker,
                    contract["primary_exchange"],
                    item["currency"],
                    item["name"],
                    contract["isin"],
                    contract["con_id"],
                )
            )
    out = io.StringIO()
    out.write(NOTE + "\n")
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(HEADER)
    writer.writerows(rows)
    return out.getvalue(), skipped


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="do not write; fail when out of date")
    args = parser.parse_args()

    if not CONTRACTS.exists():
        print(
            f"{CONTRACTS} is missing: it is the output of spike B (git-ignored).", file=sys.stderr
        )
        return 2
    text, skipped = build()
    for reason in skipped:
        print(f"skipped {reason}", file=sys.stderr)
    count = len(text.splitlines()) - 2
    if args.check:
        current = CATALOGUE.read_text(encoding="utf-8") if CATALOGUE.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{CATALOGUE} is out of date: run this tool without --check.", file=sys.stderr)
            return 1
        print(f"{CATALOGUE.name}: up to date, {count} instruments")
        return 0
    CATALOGUE.write_bytes(text.encode("utf-8"))  # bytes: keep LF on Windows
    print(f"{CATALOGUE.name}: {count} instruments written, {len(skipped)} skipped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
